/* Build the sideload ACL catalog from the SDK used for compilation.
 * NORMAL describes permissions available to third-party applications. A
 * restricted APL and provisionEnable identify permissions requiring Profile
 * authorization. Never infer availability from the permission name alone.
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const PROJECT_ROOT = path.resolve(__dirname, '..');
const DEFAULT_SDK_ROOT = '/Applications/DevEco-Studio.app/Contents/sdk';
const DEFINITIONS_PATH = path.join('openharmony', 'toolchains', 'lib', 'PermissionDefinitions.json');
const LEGACY_PROFILE_PERMISSION = 'ohos.permission.FILE_ACCESS_PERSIST';
// Three distinct sets must never be conflated: what the SDK marks as a
// restricted Profile ACL, what DevEco auto-signing is allowed to request on
// the developer's behalf, and which of those AGC has actually approved.
// The auto-apply rules below are transcribed from the bytecode of
// DevEco Studio 26.0.0.821 (build DS-261.23567.138.36.2600821); see
// docs/validation-oct13/acl-signing/deveco-evidence for the disassembly.
const AUTO_APPLY_BASE_LEVEL = 'system_basic';
const AUTO_APPLY_INCLUDE = [
  'ohos.permission.FILE_ACCESS_PERSIST',
  'ohos.permission.READ_WRITE_DOWNLOAD_DIRECTORY',
  'ohos.permission.READ_WRITE_DOCUMENTS_DIRECTORY'
];
const AUTO_APPLY_EXCLUDE = [
  'ohos.permission.READ_DOCUMENT',
  'ohos.permission.WRITE_DOCUMENT'
];
// Version whose bytecode the include/exclude lists were read from.
const DEVECO_RULE_VERSION = '26.0.0.821';

function isRecognizedAcl(row) {
  if (row.availableType !== 'NORMAL' || row.provisionEnable !== true) return false;
  // FILE_ACCESS_PERSIST and the two directory permissions are auto-apply
  // entries whose SDK level is `normal`, so the base level rule cannot admit them.
  if (row.name === LEGACY_PROFILE_PERMISSION || AUTO_APPLY_INCLUDE.includes(row.name)) return true;
  return row.availableLevel === AUTO_APPLY_BASE_LEVEL || row.availableLevel === 'system_core';
}

/** Exact IDE auto-apply predicate: explicit include, then explicit exclude, then the base rule. */
function isAutoApplicableAcl(row) {
  if (AUTO_APPLY_INCLUDE.includes(row.name)) return row.availableType === 'NORMAL' && row.provisionEnable === true;
  if (AUTO_APPLY_EXCLUDE.includes(row.name)) return false;
  return row.availableType === 'NORMAL' && row.provisionEnable === true &&
    row.availableLevel === AUTO_APPLY_BASE_LEVEL;
}

function validate(definitions) {
  if (!definitions || Array.isArray(definitions) || typeof definitions !== 'object' ||
      !Array.isArray(definitions.definePermissions) || definitions.definePermissions.length === 0) {
    throw new Error('SDK PermissionDefinitions.json must contain a non-empty definePermissions array');
  }
  const names = new Set();
  for (const row of definitions.definePermissions) {
    if (!row || Array.isArray(row) || typeof row !== 'object' || typeof row.name !== 'string' ||
        !/^ohos\.permission\.[A-Za-z0-9_]+(?:\.[A-Za-z0-9_]+)*$/.test(row.name) ||
        typeof row.availableType !== 'string' || !/^[A-Z][A-Z_]*$/.test(row.availableType) ||
        typeof row.availableLevel !== 'string' || !/^[a-z][a-z_]*$/.test(row.availableLevel) ||
        typeof row.provisionEnable !== 'boolean') {
      throw new Error('SDK permission definition has invalid name or authorization classification');
    }
    if (names.has(row.name)) throw new Error('SDK permission definition is duplicated: ' + row.name);
    names.add(row.name);
  }
  return definitions.definePermissions;
}

function build(definitions, sourceHash) {
  const rows = validate(definitions);
  if (sourceHash === undefined) sourceHash = crypto.createHash('sha256').update(JSON.stringify(definitions)).digest('hex');
  if (typeof sourceHash !== 'string' || !/^[0-9a-f]{64}$/.test(sourceHash)) {
    throw new Error('SDK permission definition SHA-256 is invalid');
  }
  const permissions = rows.filter(isRecognizedAcl).map(row => row.name).sort();
  if (permissions.length === 0) throw new Error('SDK contains no public Profile ACL permissions');
  const autoApplicable = rows.filter(isAutoApplicableAcl).map(row => row.name).sort();
  if (autoApplicable.length === 0) throw new Error('SDK contains no auto-applicable Profile ACL permissions');
  // A recognized ACL outside the auto-apply scope is not a packaging error: it
  // is a permission AGC must approve before the IDE path can sign for it.
  const manualOnly = permissions.filter(name => !autoApplicable.includes(name));
  if (autoApplicable.some(name => !permissions.includes(name))) {
    throw new Error('Auto-applicable ACL set is not a subset of the recognized ACL catalog');
  }
  const literals = list => list.map(name => "    '" + name + "'").join(',\n');
  const content = `// Generated by tools/prepare_acl_policy.cjs; regenerate with the compilation SDK.
// SDK PermissionDefinitions.json SHA-256: ${sourceHash}
// recognized: NORMAL + provisionEnable + (system_basic | system_core) plus the legacy FILE_ACCESS_PERSIST entry.
// autoApplicable: DevEco ${DEVECO_RULE_VERSION} auto-signing scope, which additionally includes
// FILE_ACCESS_PERSIST, READ_WRITE_DOWNLOAD_DIRECTORY and READ_WRITE_DOCUMENTS_DIRECTORY while excluding
// READ_DOCUMENT and WRITE_DOCUMENT. Recognize a permission is not the same as being allowed to request it.
export class SideloadAclPolicy {
  private static readonly permissions: string[] = [
${literals(permissions)}
  ];

  private static readonly autoApplicable: string[] = [
${literals(autoApplicable)}
  ];

  /** Request only ACLs actually declared by the package; the signed Profile remains authoritative. */
  static effective(requested: string[]): string[] {
    const selected: string[] = [];
    for (const raw of requested) {
      const name = raw.trim();
      if (SideloadAclPolicy.permissions.includes(name) && !selected.includes(name)) selected.push(name);
    }
    return selected.sort();
  }

  /** Declared ACLs that this SDK catalog does not recognize; they cannot be covered by a generated Profile. */
  static unrecognized(requested: string[]): string[] {
    const missing: string[] = [];
    for (const raw of requested) {
      const name = raw.trim();
      if (name.length > 0 && !SideloadAclPolicy.permissions.includes(name) && !missing.includes(name)) missing.push(name);
    }
    return missing.sort();
  }

  /** Recognized ACLs the IDE auto-signing path may request without a prior AGC approval. */
  static autoApplicableAcls(requested: string[]): string[] {
    return SideloadAclPolicy.effective(requested)
      .filter((name: string) => SideloadAclPolicy.autoApplicable.includes(name));
  }

  /** Recognized ACLs that need an AGC approval before signing can succeed. */
  static requiringApproval(requested: string[]): string[] {
    return SideloadAclPolicy.effective(requested)
      .filter((name: string) => !SideloadAclPolicy.autoApplicable.includes(name));
  }

  /** True when auto-signing plus the already approved ACLs cover every recognized requirement. */
  static covered(requested: string[], approved: string[]): boolean {
    const eligible = SideloadAclPolicy.autoApplicable;
    return SideloadAclPolicy.effective(requested)
      .every((name: string) => eligible.includes(name) || approved.includes(name));
  }
}
`;
  return { permissions, autoApplicable, manualOnly, sourceHash, content };
}

function locateDefinitions(sdkRoot) {
  if (typeof sdkRoot !== 'string' || sdkRoot.trim().length === 0) throw new Error('Compilation SDK root is missing');
  const root = path.resolve(sdkRoot);
  for (const candidate of [path.join(root, DEFINITIONS_PATH), path.join(root, 'default', DEFINITIONS_PATH)]) {
    if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) return candidate;
  }
  throw new Error('Cannot find compilation SDK PermissionDefinitions.json under ' + root);
}

function generate(options = {}) {
  if (!options || Array.isArray(options) || typeof options !== 'object') throw new Error('ACL generation options are invalid');
  // An explicitly configured SDK must be usable; silently falling back would
  // generate a policy for a different SDK than the build actually uses.
  const sdkRoot = options.sdkRoot !== undefined ? options.sdkRoot :
    process.env.DEVECO_SDK_HOME !== undefined ? process.env.DEVECO_SDK_HOME : DEFAULT_SDK_ROOT;
  const source = locateDefinitions(sdkRoot);
  const bytes = fs.readFileSync(source);
  let definitions;
  try { definitions = JSON.parse(bytes.toString('utf8')); }
  catch (_) { throw new Error('Compilation SDK PermissionDefinitions.json is not valid JSON'); }
  const result = build(definitions, crypto.createHash('sha256').update(bytes).digest('hex'));
  const projectRoot = options.projectRoot ?? PROJECT_ROOT;
  if (typeof projectRoot !== 'string' || !projectRoot.trim()) throw new Error('Native project root is missing');
  const target = path.join(path.resolve(projectRoot), 'entry', 'src', 'main', 'ets', 'data', 'SideloadAclPolicy.ets');
  const changed = !fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== result.content;
  if (changed) {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, result.content);
  }
  return { permissions: result.permissions.length, autoApplicable: result.autoApplicable.length,
    requiringApproval: result.manualOnly.length, sourceHash: result.sourceHash, source, target, changed };
}

module.exports = { validate, build, locateDefinitions, generate, isRecognizedAcl, isAutoApplicableAcl,
  AUTO_APPLY_INCLUDE, AUTO_APPLY_EXCLUDE, DEVECO_RULE_VERSION };
if (require.main === module) {
  try { process.stdout.write(JSON.stringify(generate()) + '\n'); }
  catch (error) { process.stderr.write(error.message + '\n'); process.exitCode = 1; }
}
